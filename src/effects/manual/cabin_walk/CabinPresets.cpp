const CabinLayout *FindCabinPreset(std::string_view key) {
  const auto it = std::find_if(
      std::begin(kPresets), std::end(kPresets),
      [&](const CabinPreset &preset) { return preset.key == key; });
  return it == std::end(kPresets) ? nullptr : &it->layout;
}

